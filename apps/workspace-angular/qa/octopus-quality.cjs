const {chromium}=require('playwright-core');const assert=require('node:assert/strict');
(async()=>{
const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox','--disable-dev-shm-usage']});
const page=await browser.newPage({viewport:{width:1440,height:950}});
const errors=[],decisions=[];
page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text().slice(0,300));});
const device={id:'test-node',display_name:'test-node',hostname:'test-node',platform:'Linux',architecture:'x86_64',status:'online',connected:true,permission_profile:'STANDARD',access_max_permission_profile:'STANDARD',capabilities:{filesystem:true,transfer:true,desktop:false,local_max_permission_profile:'FULL_CONTROL',privileged_helper:true}};
const records=Array.from({length:75},(_,i)=>({tool:i%3===0?'fs.read':'shell.exec',status:'ok',args_summary:'redacted',duration_ms:60+i}));
page.route('**/api/**',r=>{const req=r.request(),p=new URL(req.url()).pathname;
if(p.includes('decision'))decisions.push(req.postDataJSON());
let data={ok:true};
if(p==='/api/session')data={subject:'qa',scopes:['commandcore:full','commandcore:standard','commandcore:read'],auth_kind:'oauth2-panel'};
else if(p==='/api/devices')data={devices:[device]};
else if(p==='/api/managed-devices')data={devices:[{...device,managed_by_me:true,grants:[{subject:'qa',max_permission_profile:'STANDARD'}]}]};
else if(p==='/api/enrollment/pending')data={enrollments:[{id:'req-1',metadata:{display_name:'fresh-node',hostname:'fresh-node',platform:'Linux',architecture:'x86_64'}}]};
else if(p.includes('/inspect'))data={system_info:{cpu_logical:4,memory_total:8000000000},system_metrics:{cpu_percent:7,memory:{percent:25},disk:{percent:39}}};
else if(p.includes('/activity'))data={events:records};
else if(p==='/api/browser/sessions')data={sessions:[]};
r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(data)});});
page.route('**/install/linux-ready',r=>r.fulfill({status:200}));
await page.goto('http://commandcore-angular22-web:8080/',{waitUntil:'networkidle'});
assert.equal(await page.locator('.tile-permission').innerText(),'Access · Standard');
assert.equal(await page.locator('.brand-octopus').count(),1);
assert.equal(await page.locator('.tile-hardware-glyph').count(),1);
await page.locator('.workspace-tabs').getByRole('button',{name:/Activity/}).click();
await page.locator('.activity-scroll .operation-detail').first().waitFor();
assert.equal(await page.locator('.activity-scroll .operation-detail').count(),12);
const heights=await page.locator('.activity-scroll').evaluate(e=>({client:e.clientHeight,scroll:e.scrollHeight}));
assert(heights.client<=Math.min(560,950*.58)+4);
assert(heights.scroll>heights.client);
await page.getByRole('button',{name:'Next →'}).click();
await page.getByText('Page 2 / 7').waitFor();
await page.locator('.activity-search-label input').fill('fs.read');
await page.locator('.activity-count').getByText(/25/).waitFor();
await page.screenshot({path:'/qa/octopus-activity-screen.png',fullPage:false});
await page.locator('.workspace-tabs').getByRole('button',{name:/Files/}).click();
await page.getByText('Filesystem MCP supported').waitFor();
assert.equal(await page.locator('.file-operation').count(),12);
await page.getByRole('button',{name:/Add device/}).first().click();
await page.getByRole('button',{name:/Review pending requests/}).click();
await page.locator('.pending-item input:not([type=checkbox])').fill('ABCD-1234');
await page.locator('.pending-item select').selectOption('FULL_CONTROL');
await page.getByRole('button',{name:'Approve device'}).click();
assert.equal(decisions.length,1);
assert.equal(decisions[0].initial_permission,'FULL_CONTROL');
await page.getByRole('button',{name:/Add device/}).first().click();
await page.getByRole('button',{name:/Review pending requests/}).click();
await page.locator('.pending-item input:not([type=checkbox])').fill('BAD');
await page.getByRole('button',{name:'Approve device'}).click();
const toast=page.locator('.toast');await toast.waitFor();
assert(Number(await toast.evaluate(e=>getComputedStyle(e).zIndex))>Number(await page.locator('.sheet').evaluate(e=>getComputedStyle(e).zIndex)));
await page.screenshot({path:'/qa/octopus-modal-toast.png',fullPage:false});
console.log('PASS real permission and octopus device cards');
console.log('PASS Activity: 75 API events, 12 rendered/page, internal scrollbar, filter and pagination');
console.log('PASS Files uses real capability and file-only operation history');
console.log('PASS Enrollment initial Full Control forwarded to real backend field');
console.log('PASS toast overlays dialogs with working validation');
console.log('PAGE_ERRORS',JSON.stringify(errors));
await browser.close();if(errors.length)process.exit(2);
})().catch(e=>{console.error(e.stack);process.exit(1)});
